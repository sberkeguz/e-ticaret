-- Oturum yenileme token'ları. Token'ın kendisi değil SHA-256 özeti saklanır: veritabanı sızsa bile
-- kullanılamaz. Her kullanımda yenisiyle değiştirilir (replaced_by); daha önce kullanılmış bir
-- token tekrar gelirse çalınmış sayılır ve kullanıcının bütün oturumları kapatılır.
CREATE TABLE refresh_tokens (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash  CHAR(64)     NOT NULL UNIQUE,
    created_at  TIMESTAMPTZ  NOT NULL,
    expires_at  TIMESTAMPTZ  NOT NULL,
    revoked_at  TIMESTAMPTZ
);

CREATE INDEX ix_refresh_tokens_user ON refresh_tokens (user_id) WHERE revoked_at IS NULL;
CREATE INDEX ix_refresh_tokens_expires ON refresh_tokens (expires_at);
