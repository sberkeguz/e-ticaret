-- 1) Siparişler ve ödemeler şimdiye kadar Hibernate'in (ddl-auto=update) kendiliğinden açtığı
--    tablolardı; şema artık burada, kodla birlikte sürümlenir. Mevcut veritabanında tablolar
--    zaten var (IF NOT EXISTS atlar), yeni kurulumda burada oluşur.
--    Tarih sütunları önce saat dilimsiz açılır; 3. adım hepsini aynı şekilde UTC'ye çevirir.
CREATE TABLE IF NOT EXISTS orders (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT        NOT NULL REFERENCES users (id),
    first_name   VARCHAR(255),
    last_name    VARCHAR(255),
    phone        VARCHAR(255),
    city         VARCHAR(255),
    district     VARCHAR(255),
    neighborhood VARCHAR(255),
    address      VARCHAR(300),
    total        NUMERIC(12, 2),
    status       VARCHAR(30)   NOT NULL,
    created_at   TIMESTAMP(6)  NOT NULL
);

CREATE TABLE IF NOT EXISTS order_items (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     BIGINT        NOT NULL REFERENCES orders (id),
    product_id   BIGINT,
    product_name VARCHAR(255),
    price        NUMERIC(12, 2),
    quantity     INTEGER       NOT NULL
);

CREATE TABLE IF NOT EXISTS payments (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id            BIGINT        NOT NULL UNIQUE REFERENCES orders (id),
    token               VARCHAR(255)  UNIQUE,
    attempt_id          UUID          UNIQUE,
    last_event_sequence BIGINT,
    status              VARCHAR(30)   NOT NULL,
    created_at          TIMESTAMP(6)  NOT NULL
);

-- Ürün tablosuna da Hibernate zamanla sütun eklemişti; yeni kurulumda eksik kalmasınlar.
ALTER TABLE products
    ADD COLUMN IF NOT EXISTS stock     INTEGER      NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS image_url VARCHAR(500),
    ADD COLUMN IF NOT EXISTS origin    VARCHAR(100),
    ADD COLUMN IF NOT EXISTS active    BOOLEAN      NOT NULL DEFAULT TRUE,
    ALTER COLUMN name        TYPE VARCHAR(150),
    ALTER COLUMN description TYPE VARCHAR(2000);

-- Eski bir sürümden kalan, artık hiçbir kodun kullanmadığı boş sütunlar.
ALTER TABLE orders DROP COLUMN IF EXISTS payment_status;
ALTER TABLE orders DROP COLUMN IF EXISTS payment_token;

-- 2) Durumlar ekrandaki Türkçe yazı yerine sabit kodlarla tutulur. Yazıyı arayüz seçer.
UPDATE orders SET status = CASE status
    WHEN 'Ödeme bekliyor'     THEN 'PAYMENT_PENDING'
    WHEN 'Ödeme inceleniyor'  THEN 'PAYMENT_REVIEW'
    WHEN 'Hazırlanıyor'       THEN 'PREPARING'
    WHEN 'Kargoya verildi'    THEN 'SHIPPED'
    WHEN 'Teslim edildi'      THEN 'DELIVERED'
    WHEN 'İptal edildi'       THEN 'CANCELLED'
    WHEN 'Ödeme süresi doldu' THEN 'PAYMENT_EXPIRED'
    ELSE status
END;

ALTER TABLE orders
    ALTER COLUMN status TYPE VARCHAR(30),
    ALTER COLUMN status SET NOT NULL,
    ALTER COLUMN created_at SET NOT NULL,
    ADD CONSTRAINT ck_orders_status CHECK (status IN (
        'PAYMENT_PENDING', 'PAYMENT_REVIEW', 'PREPARING', 'SHIPPED', 'DELIVERED', 'CANCELLED', 'PAYMENT_EXPIRED'));

ALTER TABLE payments
    ADD CONSTRAINT ck_payments_status CHECK (status IN (
        'PENDING', 'PAID', 'REVIEW', 'FAILED', 'CANCELLED', 'EXPIRED', 'REFUNDED'));

-- 3) Zamanlar UTC anı olarak (timestamptz) saklanır. Eski değerler sunucunun UTC saatiyle
--    yazılmıştı (backend konteyneri UTC çalışıyor), bu yüzden UTC kabul edilerek çevrilir.
ALTER TABLE orders        ALTER COLUMN created_at    TYPE TIMESTAMPTZ USING created_at    AT TIME ZONE 'UTC';
ALTER TABLE payments      ALTER COLUMN created_at    TYPE TIMESTAMPTZ USING created_at    AT TIME ZONE 'UTC';
ALTER TABLE login_history ALTER COLUMN logged_in_at  TYPE TIMESTAMPTZ USING logged_in_at  AT TIME ZONE 'UTC';
ALTER TABLE users         ALTER COLUMN last_login_at TYPE TIMESTAMPTZ USING last_login_at AT TIME ZONE 'UTC';

-- Sık kullanılan sorgular: kullanıcının siparişleri, süresi dolan bekleyen ödemeler.
CREATE INDEX IF NOT EXISTS ix_orders_user_created ON orders (user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS ix_payments_pending_created ON payments (created_at) WHERE status = 'PENDING';
